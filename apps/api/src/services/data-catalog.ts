import { ProviderName, TelecomNetwork, formatNairaFromKobo } from '@baxato/common';

export type DataPlanCategory = 'DAILY' | 'WEEKLY' | 'MONTHLY' | 'MEGA' | 'SME';
export type DataDeliveryType = 'DIRECT' | 'SME';

export interface DataPlan {
  id: string;
  network: TelecomNetwork;
  networkName: string;
  name: string;
  dataAllowance: string;
  category: DataPlanCategory;
  dataType: DataDeliveryType;
  validity: string;
  priceKobo: bigint;
  priceNaira: number;
  discountBps: number; // e.g. 250 = 2.5%
  monnifyPlanCode: string;
  vtpassServiceId?: string;
  vtpassVariationCode?: string;
  supportedProviders: ProviderName[];
}

export interface PublicDataPlanDto {
  id: string;
  network: TelecomNetwork;
  networkName: string;
  name: string;
  dataAllowance: string;
  category: DataPlanCategory;
  dataType: DataDeliveryType;
  validity: string;
  priceKobo: string;
  priceNaira: number;
  formattedPrice: string;
  discountBps: number;
  discountPercent: string;
}

const NETWORK_DISPLAY_NAMES: Record<TelecomNetwork, string> = {
  [TelecomNetwork.MTN]: 'MTN Nigeria',
  [TelecomNetwork.AIRTEL]: 'Airtel Nigeria',
  [TelecomNetwork.GLO]: 'Globacom (Glo)',
  [TelecomNetwork.NINEMOBILE]: '9mobile',
};

const NETWORK_DISCOUNT_BPS: Record<TelecomNetwork, number> = {
  [TelecomNetwork.MTN]: 250,
  [TelecomNetwork.AIRTEL]: 250,
  [TelecomNetwork.GLO]: 300,
  [TelecomNetwork.NINEMOBILE]: 250,
};

interface PlanSeed {
  id: string;
  network: TelecomNetwork;
  name: string;
  dataAllowance: string;
  category: DataPlanCategory;
  dataType?: DataDeliveryType;
  validity: string;
  priceNaira: number;
  discountBps?: number;
  monnifyPlanCode?: string;
  vtpassServiceId?: string;
  vtpassVariationCode?: string;
  supportedProviders: ProviderName[];
}

function buildPlan(seed: PlanSeed): DataPlan {
  const dataType: DataDeliveryType =
    seed.dataType ?? (seed.category === 'SME' ? 'SME' : 'DIRECT');
  const priceKobo = BigInt(Math.round(seed.priceNaira * 100));

  return {
    id: seed.id,
    network: seed.network,
    networkName: NETWORK_DISPLAY_NAMES[seed.network],
    name: seed.name,
    dataAllowance: seed.dataAllowance,
    category: seed.category,
    dataType,
    validity: seed.validity,
    priceKobo,
    priceNaira: seed.priceNaira,
    discountBps: seed.discountBps ?? NETWORK_DISCOUNT_BPS[seed.network],
    monnifyPlanCode: seed.monnifyPlanCode ?? '',
    vtpassServiceId: seed.vtpassServiceId,
    vtpassVariationCode: seed.vtpassVariationCode,
    supportedProviders: seed.supportedProviders,
  };
}

