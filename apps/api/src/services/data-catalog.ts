export const DATA_CATEGORY_ORDER: DataPlanCategory[] = [
  'DAILY',
  'WEEKLY',
  'MONTHLY',
  'MEGA',
  'SME',
];

/**
 * Strips upstream provider-internal fields before returning plans to merchants or public APIs.
 */
export function toPublicDataPlanDto(plan: DataPlan): PublicDataPlanDto {
  return {
    id: plan.id,
    network: plan.network,
    networkName: plan.networkName,
    name: plan.name,
    dataAllowance: plan.dataAllowance,
    category: plan.category,
    dataType: plan.dataType,
    validity: plan.validity,
    priceKobo: plan.priceKobo.toString(),
    priceNaira: plan.priceNaira,
    formattedPrice: formatNairaFromKobo(plan.priceKobo),
    discountBps: plan.discountBps,
    discountPercent: (plan.discountBps / 100).toFixed(1) + '%',
  };
}

/**
 * Filters data plans strictly to the currently activated primary provider (never exposing
 * unsupported categories or bundles) plus optional network/category/dataType filters.
 */
export function filterCatalogForProvider(
  plans: DataPlan[],
  activePrimaryProvider: ProviderName,
  filters?: {
    network?: TelecomNetwork;
    category?: DataPlanCategory;
    dataType?: DataDeliveryType;
  },
): DataPlan[] {
  return plans.filter((p) => {
    if (!p.supportedProviders.includes(activePrimaryProvider)) return false;
    if (filters?.network && p.network !== filters.network) return false;
    if (filters?.category && p.category !== filters.category) return false;
    if (filters?.dataType && p.dataType !== filters.dataType) return false;
    return true;
  });
}

/**
 * Computes ordered unique categories available for a set of plans.
 */
export function getAvailableCategoriesForPlans(
  plans: Array<{ category: DataPlanCategory }>,
): DataPlanCategory[] {
  const present = new Set(plans.map((p) => p.category));
  return DATA_CATEGORY_ORDER.filter((cat) => present.has(cat));
}

